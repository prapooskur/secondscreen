macro_rules! icons {
    ($($name:ident),+ $(,)?) => {
        #[derive(Clone, Copy)]
        pub enum Icon {
            $($name),+
        }

        const ICONS: &[Icon] = &[$(Icon::$name),+];

        impl Icon {
            fn asset_path(self) -> &'static str {
                match self {
                    $(Self::$name => concat!("icons/", stringify!($name), ".svg")),+
                }
            }
        }
    };
}

